export function t(
  key: string,
  language: Language,
  vars: Record<string, string | number> = {},
): string {
  if (key.startsWith('chrome.')) {
    let text = chromeTranslation(language, key.slice(7)) ?? key;
    for (const [name, replacement] of Object.entries(vars))
      text = text.replaceAll(`{${name}}`, String(replacement));
    return text;
  }
  if (key.startsWith('wb.')) {
    let text = workbenchTranslation(language, key.slice(3)) ?? key;
    for (const [name, replacement] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(replacement));
    }
    return text;
  }
  const keys = key.split('.');
  let current: unknown = translations[language] ?? translations['zh-CN'];

  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = (current as Record<string, unknown>)[k];
    } else {
      return key;
    }
  }

  let text = typeof current === 'string' ? current : key;
  for (const [name, replacement] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(replacement));
  }
  return text;
}
